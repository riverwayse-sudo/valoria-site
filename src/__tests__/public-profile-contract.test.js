const fs = require('fs')
const path = require('path')
const read = (file) => fs.readFileSync(path.join(process.cwd(), file), 'utf8')

describe('public professional profile privacy and presentation', () => {
  test('public profile routes use only the Marketplace roster projection', () => {
    const page = read('src/app/profile/[id]/page.jsx')
    const client = read('src/app/profile/[id]/ProfileClient.jsx')
    expect(page).toContain('getConsentVerifiedPublicProfile')
    expect(page).toContain('initialProfile={initialProfile}')
    expect(page).not.toContain(".from('marketplace_public_roster')")
    expect(client).not.toContain(".from('marketplace_public_roster')")
    expect(client).toContain('if (!user || (isUuid && user.id !== id))')
    expect(client).toContain(".from('professional_profiles')")
    expect(client).toContain(".eq('id', user.id)")
    const marketplace = read('src/lib/marketplace-data.js')
    const projection = read('src/lib/public-profile.js')
    expect(marketplace).toContain("const SOURCE = 'marketplace_public_roster'")
    expect(marketplace).toContain("import 'server-only'")
    expect(marketplace).toContain('getApprovedPublicProfessionalIds')
    expect(projection).toContain("import 'server-only'")
    expect(projection).toContain(".from('marketplace_public_roster')")
    expect(projection).toContain('professional_profile_acknowledgements')
    expect(projection).toContain('PUBLIC_PROFILE_ACKNOWLEDGEMENT_VERSION')
  })

  test('homepage public profile reads never bypass roster RLS with service-role credentials', () => {
    const homepage = read('src/components/LiveProfilesScroll.jsx')
    expect(homepage).toContain('getMarketplaceDirectoryData')
    expect(homepage).not.toMatch(/SUPABASE_SERVICE_ROLE_KEY|SUPABASE_SECRET_KEY/)
    expect(read('src/lib/marketplace-data.js')).toContain("import 'server-only")
  })

  test('public profile mapping excludes private contact and account fields', () => {
    const mapper = read('src/lib/public-profile.js')
    expect(mapper).toContain('const PUBLIC_PROFILE_FIELDS')
    expect(mapper).toContain('atb_id')
    expect(mapper).not.toContain('display_name')
    expect(mapper).not.toContain('full_name')
    expect(mapper).not.toContain('phone')
    expect(mapper).not.toContain('email')
    expect(mapper).not.toContain('salary_expectation')
    expect(mapper).toContain('professional_profile_acknowledgements')
  })

  test('profile summary prioritises the VALU report and avoids unsupported verification labels', () => {
    const client = read('src/app/profile/[id]/ProfileClient.jsx')
    expect(client).toContain('VALU Capability Summary')
    expect(client).toContain('SELF-REPORTED OVERVIEW')
    expect(client).toContain('MARKETPLACE PROFILE')
    expect(client).not.toMatch(/Verified Facilitator|Verified Speaker|Registered with African Talent Bureau Ltd/)
  })
})
