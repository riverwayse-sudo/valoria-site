// src/__tests__/scoring-parity.test.js
//
// Cross-repository scoring parity.
//
// The site previously drifted from the platform contract (retired pathway
// names, and a 0.85 consistency / 0.80 gaming penalty applied to the published
// score). src/scoringEngine.js is now a mirror of
// valoria-platform/valoria-final/src/scoringEngine.js, which imports the
// canonical valuV4Contract.js.
//
// This test proves parity in two ways:
//   1. Golden vectors: result objects produced by the CANONICAL platform engine
//      (scoring-parity-vectors.json) must be reproduced field-for-field by the
//      site engine over the same fixture bank and answer sets.
//   2. Contract constants: the site contract must equal the platform's.
//
// The vectors are regenerated by running the canonical engine, never hand-edited.
// If the platform contract changes, regenerate the vectors in the same PR that
// updates src/valuV4Contract.js.

const fs = require('fs')
const path = require('path')

const siteEngine = require('../scoringEngine')
const siteContract = require('../valuV4Contract')

// The platform contract is a sibling checkout in the development workspace and a
// separate repository in CI, where it is absent. When it is present, compare against
// the real file: a hand-copied literal cannot notice the platform drifting, which is
// exactly the failure this suite exists to prevent.
function resolvePlatformContract() {
  const candidates = [
    process.env.VALORIA_PLATFORM_DIR,
    '/workspace/repos/valoria-platform',
    '/workspace/project/valoria-platform',
    path.join(__dirname, '..', '..', '..', 'valoria-platform'),
  ].filter(Boolean)
  for (const d of candidates) {
    const file = path.join(d, 'valoria-final', 'src', 'valuV4Contract.js')
    if (fs.existsSync(file)) return file
  }
  return null
}

const PLATFORM_CONTRACT_FILE = resolvePlatformContract()

// Canonical constants copied from valoria-platform/valoria-final/src/valuV4Contract.js.
const PLATFORM_CONTRACT = {
  VALU_VERSION: 4,
  MAX_SCORE: 100,
  MARKETPLACE_SCORE_THRESHOLD: 35,
  CLUSTERS: [
    { id: 'P', name: 'Presence', weight: 0.20, maxRaw: 36 },
    { id: 'R', name: 'Relationships', weight: 0.25, maxRaw: 48 },
    { id: 'I', name: 'Intelligence', weight: 0.25, maxRaw: 60 },
    { id: 'M', name: 'Mastery', weight: 0.20, maxRaw: 36 },
    { id: 'E', name: 'Enterprise', weight: 0.10, maxRaw: 36 },
  ],
  DESIGNATIONS: [
    { min: 90, name: 'Elite' },
    { min: 75, name: 'Distinguished' },
    { min: 55, name: 'Proficient' },
    { min: 35, name: 'Standard' },
  ],
  PATHWAYS: [
    { min: 75, name: 'Advanced Development Pathway' },
    { min: 55, name: 'Cluster Development Pathway' },
    { min: 35, name: 'Foundation Development Pathway' },
    { min: 0, name: 'Assessment Follow-up Pathway' },
  ],
}

// Fixture bank shaped like the canonical 58-question bank: five scored clusters
// plus validity anchors (excluded from scoring) and two futureReady items.
const FIXTURE_BANK = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'fixtures', 'scoring-fixture-bank.json'), 'utf8')
)

const VECTORS = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'scoring-parity-vectors.json'), 'utf8')
)

describe('site scoring contract equals the canonical platform contract', () => {
  test('scalar constants match', () => {
    expect(siteContract.VALU_VERSION).toBe(PLATFORM_CONTRACT.VALU_VERSION)
    expect(siteContract.MAX_SCORE).toBe(PLATFORM_CONTRACT.MAX_SCORE)
    expect(siteContract.MARKETPLACE_SCORE_THRESHOLD).toBe(PLATFORM_CONTRACT.MARKETPLACE_SCORE_THRESHOLD)
    expect(siteEngine.SKILL_MAX_RAW).toBe(12)
  })

  test('cluster ids, names, weights and maxRaw match exactly', () => {
    expect(siteContract.CLUSTERS.map(c => ({ id: c.id, name: c.name, weight: c.weight, maxRaw: c.maxRaw })))
      .toEqual(PLATFORM_CONTRACT.CLUSTERS)
    expect(siteContract.CLUSTERS.reduce((s, c) => s + c.weight, 0)).toBeCloseTo(1, 10)
  })

  test('merit bands match, including the Standard floor at 35', () => {
    expect(siteContract.DESIGNATIONS.map(d => ({ min: d.min, name: d.name })))
      .toEqual(PLATFORM_CONTRACT.DESIGNATIONS)
  })

  test('development pathways match the canonical bands', () => {
    expect(siteContract.PATHWAYS.map(p => ({ min: p.min, name: p.name })))
      .toEqual(PLATFORM_CONTRACT.PATHWAYS)
  })
})

describe('site engine reproduces the canonical platform engine exactly', () => {
  test.each(VECTORS.map(v => [v.name, v]))('vector %s matches field-for-field', (_name, vector) => {
    const actual = siteEngine.computeResults(vector.answers, vector.timings, {}, FIXTURE_BANK)
    // Every field the canonical engine returns must be byte-identical. This
    // catches silent score mutation and any new/renamed output field.
    expect(Object.keys(actual).sort()).toEqual(Object.keys(vector.expect).sort())
    for (const key of Object.keys(vector.expect)) {
      expect({ [key]: actual[key] }).toEqual({ [key]: vector.expect[key] })
    }
  })

  test('the published index is never mutated by integrity signals', () => {
    const anchorsLow = VECTORS.find(v => v.name === 'anchors-low')
    const actual = siteEngine.computeResults(anchorsLow.answers, anchorsLow.timings, {}, FIXTURE_BANK)
    expect(actual.gamingDetected).toBe(true)
    // The canonical engine computes the index from clusters only; the old site
    // engine would have multiplied this by 0.80.
    expect(actual.valuIndex).toBe(siteEngine.computeWeightedIndex(actual.clusterScores))
    expect(actual.valuIndex).toBe(anchorsLow.expect.valuIndex)
  })
})

// Skipped, not passed, when the sibling repository is unavailable - a skipped check is
// honest; a check that cannot see the other repository and reports success is not.
const describeLive = PLATFORM_CONTRACT_FILE ? describe : describe.skip
if (!PLATFORM_CONTRACT_FILE) {
  console.warn(
    'live scoring parity SKIPPED: no valoria-platform checkout found.\n' +
      '  Set VALORIA_PLATFORM_DIR=/path/to/valoria-platform to run it.'
  )
}

describeLive('the site contract equals the live platform contract', () => {
  const live = require(PLATFORM_CONTRACT_FILE)
  const liveContract = live.default || live
  const shape = (c) => ({
    VALU_VERSION: c.VALU_VERSION,
    MAX_SCORE: c.MAX_SCORE,
    MARKETPLACE_SCORE_THRESHOLD: c.MARKETPLACE_SCORE_THRESHOLD,
    CLUSTERS: c.CLUSTERS.map((x) => ({ id: x.id, name: x.name, weight: x.weight, maxRaw: x.maxRaw })),
    DESIGNATIONS: c.DESIGNATIONS.map((d) => ({ min: d.min, name: d.name })),
    PATHWAYS: c.PATHWAYS.map((p) => ({ min: p.min, name: p.name })),
  })

  test('the copied fixture still matches the platform source it was copied from', () => {
    expect(shape(siteContract)).toEqual(shape(liveContract))
    // And the live source must still agree with the literal the earlier tests use.
    expect(shape(liveContract)).toEqual(PLATFORM_CONTRACT)
  })
})
