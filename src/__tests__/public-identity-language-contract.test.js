const fs = require('fs')
const path = require('path')

const read = file => fs.readFileSync(path.join(process.cwd(), file), 'utf8')

describe('Public identity and audience-language contract', () => {
  const marketplaceData = read('src/lib/marketplace-data.js')
  const publicProfile = read('src/lib/public-profile.js')
  const directory = read('src/components/MarketplaceDirectory.jsx')
  const profilePage = read('src/app/profile/[id]/page.jsx')
  const profileLayout = read('src/app/profile/[id]/layout.jsx')
  const profileClient = read('src/app/profile/[id]/ProfileClient.jsx')
  const homepage = read('src/app/page.jsx')
  const about = read('src/app/about-us/page.jsx')
  const spotlight = read('src/app/atb-spotlight/page.jsx')
  const privacy = read('src/app/privacypolicy/page.jsx')
  const homepageMarketplace = read('src/components/LiveProfilesScroll.jsx')

  test('public marketplace projections and profile metadata use ATB IDs, not personal names', () => {
    expect(marketplaceData).not.toContain('full_name')
    expect(publicProfile).not.toContain('full_name')
    expect(publicProfile).not.toContain('display_name')
    expect(publicProfile).not.toContain('email')
    expect(publicProfile).not.toContain('phone')
    expect(publicProfile).not.toContain('cv_url')
    expect(publicProfile).not.toContain('salary_expectation')
    expect(publicProfile).toContain('getConsentVerifiedPublicProfile')
    expect(publicProfile).toContain('validAtbId')
    expect(directory).not.toContain('p.full_name')
    expect(directory).not.toContain('profile.full_name')
    expect(directory).toContain('identifier: profile.atb_id')
    expect(profilePage).toContain('getConsentVerifiedPublicProfile(id, isUuid ? \'id\' : \'atb_id\')')
    expect(profileLayout).toContain('profile.atb_id')
  })

  test('public pages do not expose internal buyer or access-state terminology', () => {
    expect(spotlight).not.toMatch(/training buyers/i)
    expect(about.toLowerCase()).not.toContain('buyer')
    expect(homepage).not.toMatch(/training buyers/i)
    expect(homepageMarketplace.toLowerCase()).not.toContain('buyer')
    expect(homepageMarketplace.toLowerCase()).not.toContain('programme')
    expect(homepageMarketplace.toLowerCase()).not.toContain('organiser')
    expect(homepage).toContain("label: 'PROFESSIONAL DISCOVERY'")
    expect(profileClient).not.toContain('p.display_name')
    expect(profileClient).not.toContain('getInitials(p.display_name)')
    expect(directory).not.toContain('BASIC ACCESS')
    expect(directory).not.toContain('BASIC · SNAPSHOT')
  })

  test('the privacy page states the data-sale position and public identity boundary', () => {
    expect(privacy).toContain('We do not sell personal data.')
    expect(privacy).toContain('your ATB ID, professional headline')
    expect(privacy).toContain('Personal names are not displayed on public profile cards or pages.')
    const consent = read('src/lib/profile-consent-copy.js')
    expect(consent).toContain('public-profile-visibility-v4-2026-11-11')
    expect(consent).toContain('my ATB ID')
    expect(consent).toContain('PRIME cluster insights and development areas')
    expect(consent).not.toContain('my professional name')
  })
})
