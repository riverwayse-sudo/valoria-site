export function getInsight(slug) {
  return INSIGHTS.find(item => item.slug === slug)
}

export function getRelatedInsights(current, limit = 3) {
  if (!current) return []
  const scored = INSIGHTS.filter(item => item.slug !== current.slug).map(item => ({
    item,
    score: item.tags.filter(tag => current.tags.includes(tag)).length + (item.category === current.category ? 2 : 0),
  }))
  return scored.sort((a, b) => b.score - a.score).slice(0, limit).map(({ item }) => item)
}
